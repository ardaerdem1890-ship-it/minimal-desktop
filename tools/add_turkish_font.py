import re, io

p='include/vga_font.h'
s=io.open(p,encoding='utf-8').read()
data=[int(x,16) for x in re.findall(r'0x([0-9A-Fa-f]{2})',s)]
assert len(data)==8192

# Turkish glyphs: 8 rows each (bits: MSB = leftmost pixel)
G={
 0x80:[0x00,0x00,0x3C,0x66,0x66,0x66,0x3F,0x00],  # ğ  (g with breve)
 0x81:[0x00,0x00,0x18,0x3C,0x66,0x66,0x3E,0x00],  # ü  (u umlaut)
 0x82:[0x00,0x00,0x3E,0x66,0x66,0x66,0x66,0x01],  # ş  (s cedilla)
 0x83:[0x00,0x00,0x0C,0x18,0x18,0x18,0x0C,0x00],  # ı  (dotless i)
 0x84:[0x00,0x00,0x3C,0x66,0x66,0x66,0x3C,0x00],  # ö
 0x85:[0x00,0x00,0x3E,0x60,0x60,0x60,0x60,0x00],  # ç  (c cedilla)
 0x86:[0x18,0x18,0x00,0x7E,0x18,0x18,0x18,0x18],  # İ  (I with dot)
 0x87:[0x00,0x00,0x18,0x3C,0x66,0x7E,0x66,0x00],  # Ü
 0x88:[0x00,0x00,0x7E,0x60,0x60,0x60,0x60,0x01],  # Ş
 0x89:[0x00,0x00,0x3C,0x66,0x7E,0x66,0x66,0x00],  # Ö
 0x8A:[0x00,0x00,0x3E,0x60,0x60,0x60,0x60,0x01],  # Ç
 0x8B:[0x00,0x3C,0x00,0x3E,0x60,0x3E,0x66,0x3C],  # Ğ
}
for ch,rows in G.items():
    off=ch*32
    for i,v in enumerate(rows):
        data[off+i]=v
        # planes 0,1,3 empty for these glyphs
        for plane in (0,1,3):
            data[off+8*plane+i]=0

out=io.StringIO()
out.write('/* Standard IBM VGA 8x8 font + Turkish glyphs at 0x80-0x8B.\n')
out.write(' * 32 bytes/glyph: plane0 rows 0-7, plane1 8-15, plane2 16-23, plane3 24-31.\n')
out.write(' */\n#pragma once\n#include "types.h"\n\nstatic const u8 vga_builtin_font[8192] = {\n')
for i in range(0,8192,16):
    out.write('    '+', '.join('0x%02X'%b for b in data[i:i+16])+',\n')
out.write('};\n')
io.open(p,'w',encoding='utf-8').write(out.getvalue())
print('font patched with',len(G),'Turkish glyphs')
