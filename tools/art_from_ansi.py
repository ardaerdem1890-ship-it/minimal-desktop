#!/usr/bin/env python3
"""Turn the ANSI-coloured splash art the user pasted into an earlier chat into
include/bootart.h (VGA text-mode cells).

The reference is build/bootart_ref.txt. Each cell becomes
    { char, fg | bg << 4 }
where the characters are half/full blocks and shades, matching the 8x8 VGA font.
"""
import io
import re
import os

ANSI_FG = {30: 0, 31: 4, 32: 2, 33: 6, 34: 1, 35: 5, 36: 3, 37: 7,
           90: 8, 91: 12, 92: 10, 93: 14, 94: 9, 95: 13, 96: 11, 97: 15}
ANSI_BG = {40: 0, 41: 4, 42: 2, 43: 6, 44: 1, 45: 5, 46: 3, 47: 7,
           100: 8, 101: 12, 102: 10, 103: 14, 104: 9, 105: 13,
           106: 11, 107: 15}

GLYPH = {
    ' ': 0x20,
    '▄': 0xDF,      # lower half block
    '▀': 0xDC,      # upper half block
    '█': 0xDB,      # full block
    '░': 0xB1,      # light shade
    '▒': 0xB2,      # medium shade
    '▓': 0xB3,      # dark shade
}

ESC = re.compile(r'\x1b\[([0-9;]*)m')


def parse(text):
    rows = []
    for raw in text.split('\n'):
        cells = []
        fg, bg = 7, 0
        pos = 0
        for m in ESC.finditer(raw):
            for ch in raw[pos:m.start()]:
                if ch in GLYPH:
                    cells.append((GLYPH[ch], fg, bg))
                elif ch == '\r':
                    pass
            codes = m.group(1).split(';') if m.group(1) else ['0']
            for c in codes:
                c = c.strip()
                if not c:
                    continue
                n = int(c)
                if n == 0:
                    fg, bg = 7, 0
                elif n in ANSI_FG:
                    fg = ANSI_FG[n]
                elif n in ANSI_BG:
                    bg = ANSI_BG[n]
            pos = m.end()
        for ch in raw[pos:]:
            if ch in GLYPH:
                cells.append((GLYPH[ch], fg, bg))
        rows.append(cells)
    while rows and not rows[-1]:
        rows.pop()
    return rows


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, '..', 'build', 'bootart_ref.txt')
    text = io.open(src, encoding='utf-8').read()
    marker = 'make the text that appears on boot say the following'
    text = text.split(marker, 1)[1]
    # drop everything after the art (trailing chatter)
    rows = parse(text)
    width = max(len(r) for r in rows)
    # trim trailing blank cells
    for r in rows:
        while r and r[-1][0] == 0x20:
            r.pop()
    width = max(len(r) for r in rows)

    out = io.StringIO()
    out.write("/* Generated by tools/art_from_ansi.py from the splash art in build/bootart_ref.txt */\n")
    out.write("#pragma once\n#include \"types.h\"\n\n")
    out.write("typedef struct { u8 ch; u8 attr; } bootart_cell_t;\n\n")
    for i, r in enumerate(rows):
        out.write("static const bootart_cell_t bootart_row%d[] = {\n" % i)
        for k in range(0, len(r), 10):
            chunk = r[k:k + 10]
            out.write("    " + ", ".join("{0x%02X,0x%02X}" % (c, (fg | (bg << 4))) for c, fg, bg in chunk) + ",\n")
        out.write("};\n\n")
    out.write("static const bootart_cell_t *const bootart_rows[] = {\n")
    for i in range(len(rows)):
        out.write("    bootart_row%d,\n" % i)
    out.write("};\n")
    out.write("static const u8 bootart_widths[] = { %s };\n" % ", ".join(str(len(r)) for r in rows))
    out.write("#define BOOTART_ROWS %d\n" % len(rows))
    out.write("#define BOOTART_COLS %d\n" % width)

    io.open(os.path.join(here, '..', 'include', 'bootart.h'), 'w', encoding='utf-8').write(out.getvalue())
    print('bootart: %d rows x %d cols' % (len(rows), width))
    for r in rows:
        print(''.join('#' if c else '.' for c, _, _ in r))


if __name__ == '__main__':
    main()
