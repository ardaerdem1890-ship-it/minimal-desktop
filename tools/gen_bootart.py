#!/usr/bin/env python3
"""Generate the Minimal Desktop boot wordmark as VGA text-mode cell art.

The wordmark is drawn on a 12 x 6 half-block grid so every text row carries
two colour bands: the result is the white -> cyan -> blue gradient wordmark
shown on the splash screen.
"""
import io

# 12 half-rows tall, 6 cells wide.
FONT = {
    'M': ["#    #", "##  ##", "##  ##", "# ## #", "# ## #", "#    #",
          "#    #", "#    #", "#    #", "#    #", "#    #", "#    #"],
    'I': ["######", "######", "  ##  ", "  ##  ", "  ##  ", "  ##  ",
          "  ##  ", "  ##  ", "  ##  ", "  ##  ", "  ##  ", "  ##  "],
    'N': ["#    #", "##   #", "##   #", "# #  #", "# #  #", "#  # #",
          "#  # #", "#   ##", "#   ##", "#    #", "#    #", "#    #"],
    'A': [" #### ", "#    #", "#    #", "#    #", "#    #", "######",
          "#    #", "#    #", "#    #", "#    #", "#    #", "#    #"],
    'L': ["#     ", "#     ", "#     ", "#     ", "#     ", "#     ",
          "#     ", "#     ", "#     ", "#     ", "######", "######"],
    'O': [" #### ", "#    #", "#    #", "#    #", "#    #", "#    #",
          "#    #", "#    #", "#    #", "#    #", "#    #", " #### "],
    'S': ["######", "#     ", "#     ", "#     ", "#     ", " #### ",
          "     #", "     #", "     #", "     #", "     #", "######"],
}

TEXT = "MINIMAL OS"
GAP = 1        # cells between letters
SPACE = 2      # cells for the word space

# 12 colour bands, top to bottom (VGA 16-colour indices).
BANDS = [15, 15, 11, 11, 11, 3, 3, 9, 9, 1, 1, 1]


def build():
    cols = 0
    for i, ch in enumerate(TEXT):
        cols += SPACE if ch == ' ' else 6
        if i + 1 < len(TEXT) and TEXT[i] != ' ' and TEXT[i + 1] != ' ':
            cols += GAP
    grid = [[False] * cols for _ in range(12)]
    x = 0
    for i, ch in enumerate(TEXT):
        if ch == ' ':
            x += SPACE
            continue
        glyph = FONT[ch]
        for y in range(12):
            for gx in range(6):
                grid[y][x + gx] = glyph[y][gx] == '#'
        x += 6
        if i + 1 < len(TEXT) and ch != ' ' and TEXT[i + 1] != ' ':
            x += GAP
    return grid, cols


def main():
    grid, cols = build()
    rows = 6
    out = io.StringIO()
    out.write("/* Generated by tools/gen_bootart.py - do not edit by hand. */\n")
    out.write("#pragma once\n#include \"types.h\"\n\n")
    out.write("typedef struct { u8 ch; u8 attr; } bootart_cell_t;\n\n")

    for r in range(rows):
        top, bot = grid[r * 2], grid[r * 2 + 1]
        ct, cb = BANDS[r * 2], BANDS[r * 2 + 1]
        cells = []
        for c in range(cols):
            t, b = top[c], bot[c]
            if t and b:
                cells.append((0xDB, ct if ct == cb else ct))
            elif t:
                cells.append((0xDC, ct))          # upper half block
            elif b:
                cells.append((0xDF, cb))          # lower half block
            else:
                cells.append((0x20, 0x00))
        out.write("static const bootart_cell_t bootart_row%d[] = {\n" % r)
        for i in range(0, len(cells), 12):
            chunk = cells[i:i + 12]
            out.write("    " + ", ".join("{0x%02X,0x%02X}" % cc for cc in chunk) + ",\n")
        out.write("};\n\n")

    out.write("static const bootart_cell_t *const bootart_rows[] = {\n")
    for r in range(rows):
        out.write("    bootart_row%d,\n" % r)
    out.write("};\n")
    out.write("static const u8 bootart_widths[] = { %s };\n" %
              ", ".join([str(cols)] * rows))
    out.write("#define BOOTART_ROWS %d\n" % rows)
    out.write("#define BOOTART_COLS %d\n" % cols)

    io.open('include/bootart.h', 'w', encoding='utf-8').write(out.getvalue())
    print("wordmark: %d columns x %d rows" % (cols, rows))


main()
